#!/usr/bin/env python3
"""Real-terraform regression test for Phase 3 of docs/design/
unified-terraform-projection.md (ADR-0035) — `find_secret_paths()`/
`rewrite_strata_payload()`. A stubbed `run_command` can never prove this:
the claim under test is what a real `terraform plan` sees, not what
strata's own diagnostics report (same reasoning `test_terraform_variable_
precedence.py` documents for its own real-terraform tests).

Neither function is called through `build_run()`/`deploy_run()` here —
`rewrite_strata_payload()` is wired into `deploy_controller.py` (Phase
7), but this test calls it directly against a synthetic build-time
payload and a hand-written minimal root module (`variable "strata"`/
`variable "strata_secrets"`), isolating the delivery channel itself from
the rest of the deploy pipeline. The two outputs this root declares are
exactly the two read patterns the `strata_locals.tf` generator (Phase 6,
still not auto-generated by `build run` itself) produces: a direct
`var.strata.*` read (must see only the sentinel) and a
`var.strata_secrets[path]` read (must see the real value) — proving the
delivery channel itself works correctly independent of whether the merge
generator's output is actually present in a given root.
"""

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

from strata.integrations.terraform_projection import rewrite_strata_payload

ROOT_MODULE = """
variable "strata" {
  type = any
}

variable "strata_secrets" {
  type      = map(string)
  default   = {}
  sensitive = true
}

output "api_token_from_raw_var" {
  value = var.strata.providers.kamatera.configuration.api_token
}

output "api_token_from_secrets_map" {
  value     = var.strata_secrets["providers.kamatera.configuration.api_token"]
  sensitive = true
}

output "non_secret_sibling" {
  value = var.strata.providers.kamatera.region
}
"""


def _terraform_available() -> bool:
    return shutil.which("terraform") is not None


@pytest.mark.skipif(not _terraform_available(), reason="terraform not on PATH")
def test_rewrite_strata_payload_real_plan_sees_secret_only_via_strata_secrets(tmp_path: Path):
    root = tmp_path / "root"
    root.mkdir()
    (root / "main.tf").write_text(ROOT_MODULE, encoding="utf-8")

    payload = {
        "providers": {
            "kamatera": {
                "type": "kamatera",
                "region": "eu",
                "configuration": {"api_token": "${secret:API_TOKEN}"},
            }
        },
    }
    resolved, secrets = rewrite_strata_payload(payload, {"API_TOKEN": "super-secret-value"})

    tfvars_file = root / "strata.auto.tfvars.json"
    tfvars_file.write_text(json.dumps({"strata": resolved}), encoding="utf-8")

    # The on-disk file itself must never carry the real value — the whole
    # point of the sentinel (ADR-0031: resolved secret values never touch
    # disk). A direct text scan, not just asserting on `resolved`'s intent.
    assert "super-secret-value" not in tfvars_file.read_text(encoding="utf-8")

    env = {**os.environ, "TF_VAR_strata_secrets": json.dumps(secrets)}
    subprocess.run(["terraform", "init", "-input=false"], cwd=root, env=env, capture_output=True, text=True, check=True)
    subprocess.run(
        ["terraform", "plan", "-input=false", "-out=tfplan"],
        cwd=root,
        env=env,
        capture_output=True,
        text=True,
        check=True,
    )
    shown = subprocess.run(
        ["terraform", "show", "-json", "tfplan"], cwd=root, env=env, capture_output=True, text=True, check=True
    )
    outputs = json.loads(shown.stdout)["planned_values"]["outputs"]

    # A `.tf` consumer that reads `var.strata.*` directly (bypassing the
    # future strata_locals.tf merge entirely) gets the sentinel — visibly
    # wrong and greppable, never the real value and never a crash.
    assert outputs["api_token_from_raw_var"]["value"] == "__strata_secret__:providers.kamatera.configuration.api_token"
    # The real value is only ever reachable via TF_VAR_strata_secrets.
    assert outputs["api_token_from_secrets_map"]["value"] == "super-secret-value"
    # A non-secret sibling in the same nested object resolves normally.
    assert outputs["non_secret_sibling"]["value"] == "eu"
